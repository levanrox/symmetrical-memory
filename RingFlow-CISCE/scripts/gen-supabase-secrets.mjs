#!/usr/bin/env node
/**
 * Generates the secrets a self-hosted Supabase Realtime setup needs and writes
 * any *missing* ones to `.env` (never overwrites existing values).
 *
 *   node scripts/gen-supabase-secrets.mjs
 *
 * What it creates in `.env`:
 *   POSTGRES_PASSWORD            password for the compose `db` service
 *                                (URL-safe alphanumeric; also used in DATABASE_URL)
 *   SUPABASE_JWT_SECRET          signs the anon/service-role JWTs; must match the
 *                                realtime container's API_JWT_SECRET
 *   SECRET_KEY_BASE              Phoenix secret for the realtime container
 *   NEXT_PUBLIC_SUPABASE_ANON_KEY    public anon JWT (safe to expose)
 *   SUPABASE_SERVICE_ROLE_KEY        service-role JWT (server only, never public)
 *   SESSION_SECRET               signs the app's admin/mod session cookies
 *                                (64 hex chars; never rotated once set)
 *
 * Both `docker compose` and Next.js read `.env`, so one file serves both.
 * Machine-specific overrides (LAN IP, host-vs-container URLs) go in
 * `.env.local` — see `.env.example`.
 */

import { randomBytes, createHmac } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ENV_PATH = resolve(process.cwd(), ".env");

function base64url(buf) {
  return buf
    .toString("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/, "");
}

/** Minimal HS256 JWT signer — no dependencies needed. */
function signJwt(payload, secret) {
  const header = base64url(Buffer.from(JSON.stringify({ alg: "HS256", typ: "JWT" })));
  const body = base64url(Buffer.from(JSON.stringify(payload)));
  const sig = base64url(createHmac("sha256", secret).update(`${header}.${body}`).digest());
  return `${header}.${body}.${sig}`;
}

/** URL-safe password (safe to embed in DATABASE_URL). */
function genPassword() {
  return base64url(randomBytes(24));
}

function parseEnv(text) {
  const values = new Map();
  for (const line of text.split("\n")) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (m) values.set(m[1], m[2].replace(/^["']|["']$/g, ""));
  }
  return values;
}

function main() {
  const existing = existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, "utf8")) : new Map();
  const added = [];

  const ensure = (key, gen) => {
    if (!existing.has(key) || existing.get(key) === "") {
      const value = gen();
      existing.set(key, value);
      added.push(key);
    }
  };

  ensure("POSTGRES_PASSWORD", genPassword);
  ensure("SUPABASE_JWT_SECRET", () => randomBytes(32).toString("hex"));
  ensure("SECRET_KEY_BASE", () => randomBytes(64).toString("hex"));
  ensure("SESSION_SECRET", () => randomBytes(32).toString("hex"));

  // The anon/service-role keys must be HS256 JWTs signed with SUPABASE_JWT_SECRET.
  const jwtSecret = existing.get("SUPABASE_JWT_SECRET");
  const farFuture = 2_500_000_000; // ~2049
  ensure("NEXT_PUBLIC_SUPABASE_ANON_KEY", () =>
    signJwt({ iss: "supabase", role: "anon", exp: farFuture }, jwtSecret)
  );
  ensure("SUPABASE_SERVICE_ROLE_KEY", () =>
    signJwt({ iss: "supabase", role: "service_role", exp: farFuture }, jwtSecret)
  );

  if (added.length === 0) {
    console.log("All secrets already present in .env — nothing to do.");
    return;
  }

  const header = `# ── RingFlow secrets ────────────────────────────────────────────────────
# Generated by scripts/gen-supabase-secrets.mjs — do not commit this file.
# Do not edit by hand unless you know what you are doing: the anon and
# service-role keys are JWTs signed with SUPABASE_JWT_SECRET and must stay
# in sync with the realtime container's API_JWT_SECRET.
`;
  let out = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : header;
  if (!out.endsWith("\n")) out += "\n";
  for (const key of added) {
    out += `${key}=${existing.get(key)}\n`;
  }
  writeFileSync(ENV_PATH, out);

  console.log(`Wrote ${added.length} secret(s) to .env: ${added.join(", ")}`);
  console.log("");
  console.log("Next steps:");
  console.log("  ./scripts/start-event.sh   (one-command event-day startup)");
  console.log("");
  console.log("Manual equivalent:");
  console.log("  1. docker compose up -d db pooler");
  console.log("  2. docker compose up migrate");
  console.log("  3. docker compose up -d realtime app");
  console.log("  4. Seed data from the host if this is a fresh DB (DATABASE_URL in .env.local):");
  console.log("       npm run db:push && npm run db:seed");
  console.log("  5. For LAN clients, set NEXT_PUBLIC_REALTIME_URL=http://<server-lan-ip>:4000");
  console.log("     in .env.local (host run) or .env (compose build) — see .env.example.");
}

main();
