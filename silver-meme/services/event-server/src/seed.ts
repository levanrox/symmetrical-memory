/**
 * Seeds a tournament that is worth exploring.
 *
 *   pnpm seed
 *
 * Idempotent: it does nothing if an event already exists. To start over, run
 * `pnpm db:reset` and seed again.
 *
 * What it leaves behind, deliberately, is a spread of states rather than one
 * tidy happy path:
 *
 *   - a 16-entrant category, drawn, locked and on a ring, so a deeper two-rung
 *     repechage can be seen;
 *   - an 8-entrant category, drawn and locked, for the standard two bronzes;
 *   - a 5-entrant category, drawn and locked, where byes are visible;
 *   - two categories with no draw at all, so a draw can be generated by hand;
 *   - a small category already played out, so the results page and the medal
 *     table are not empty.
 *
 * Clubs repeat across entrants on purpose: club separation only has something
 * to do when they do.
 */

